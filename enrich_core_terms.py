def main() -> None:
    payload = json.loads(PATH.read_text(encoding="utf-8"))
    terms = payload["terms"]
    found = set()
    for term in terms:
        name = term.get("name_ko")
        update = UPDATES.get(name)
        if not update:
            continue
        term.update(update)
        pieces = [
            term.get("name_ko", ""),
            term.get("name_en", ""),
            " ".join(term.get("aliases", [])),
            term.get("category", ""),
            term.get("summary", ""),
            term.get("detail", ""),
            term.get("formula", ""),
            term.get("unit", ""),
            term.get("example", ""),
            term.get("caution", ""),
            " ".join(term.get("related", [])),
        ]
        term["search_text"] = " ".join(x for x in pieces if x)
        found.add(name)
    payload["version"] = "2.0.0"
    payload["count"] = len(terms)
    PATH.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")
    missing = sorted(set(UPDATES) - found)
    print(f"Enhanced {len(found)} terms; missing={missing}")


if __name__ == "__main__":
    main()
